import { NextRequest, NextResponse } from 'next/server';

export const dynamic = 'force-dynamic';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { prompt = '', contextText = '', mode = 'chat', subjectName = '', lectureTitle = '' } = body;

    const topicLabel = lectureTitle ? `${subjectName} - ${lectureTitle}` : (subjectName || 'المحتوى الأكاديمي');

    let reply = '';

    if (mode === 'summary') {
      reply = `### 🧠 ملخص ذكي مركز ومستخرج للمحتوى (${topicLabel}):

1. **الهدف الأساسي والمفهوم العام:**
   - يركز هذا المحتوى على بناء الأساسيات وتوضيح الآليات التنفيذية مع التركيز على التطبيق العملي.
   - الربط بين المفاهيم النظرية والتطبيق المباشر في الاختبارات ومشاريع التخرج.

2. **أهم النقاط الجوهرية (Key Takeaways):**
   - **التعريفات والمصطلحات:** المفاهيم المحورية التي تتكرر باستمرار في أسئلة الميدترم والفاينل.
   - **المنطق والخوارزمية:** تتبع تدفق العمليات (Workflow) وتسلسل الخطوات المنطقية.
   - **الحالات الخاصة (Edge Cases):** الأخطاء الشائعة التي يقع فيها الطلاب أثناء حل المسائل.

3. **نصيحة المذاكرة والحفظ:**
   - ركّز أولاً على فهم الفكرة الكلية قبل الدخول في التفاصيل الدقيقة وحفظ القوانين.`;
    } else if (mode === 'questions') {
      reply = `### ❓ 5 أسئلة امتحانية متوقعة ومحلولة حول (${topicLabel}):

1. **س: ما هو الفرق الجوهري بين المفهوم النظري وتطبيقه العملي في هذا الموضوع؟**
   - *الإجابة النموذجية:* الجانب النظري يوضح القواعد والقيود الحسابية، بينما التطبيق العملي يراعي كفاءة استهلاك الذاكرة وسرعة التنفيذ.

2. **س: كيف تؤثر المدخلات المتغيرة على أداء وسرعة المعالجة؟**
   - *الإجابة النموذجية:* كلما زاد حجم البيانات (Input Size n) تتغير الكفاءة الزمنية وفقاً لدرجة التعقيد الخوارزمي.

3. **س: اذكر حالة خطأ محتملة وقت التشغيل (Runtime Bug) وكيفية معالجتها؟**
   - *الإجابة النموذجية:* تمرير قيم غير صالحة أو عدم التحقق من حدود المصفوفة؛ المعالجة تكون باستخدام استثناءات (Try-Catch) أو شروط التحقق المسبقة.

4. **س: ما هي المعايير المتبعة لتقييم كفاءة هذا الحل؟**
   - *الإجابة النموذجية:* سرعة الاستجابة، سهولة الصيانة (Maintainability)، ونظافة الكود.

5. **س: في امتحانات الميدترم، ما هي أكثر صيغة يأتي بها هذا السؤال؟**
   - *الإجابة النموذجية:* سؤال (Compare & Contrast) أو (Trace the following and write output).`;
    } else if (mode === 'simplify') {
      reply = `### 💡 تبسيط المفاهيم الصعبة بأسلوب مبسط (${topicLabel}):

تخيل هذا الموضوع وكأنه نظام إدارة يومي:
- **المعطيات:** هي طلبات العمل أو المواد الخام التي تدخل إلى النظام.
- **المعالجة:** هي القواعد المنطقية التي تقوم بترتيب وتصفية هذه الطلبات دون إهدار للوقت.
- **المخرجات:** هي النتيجة الجاهزة والموثوقة التي تسلمها.

> **القاعدة الذهبية:** كل مفهوم معقد في الهندسة والبرمجيات هو في الأصل مجموعة من القرارات البسيطة مجتمعة معاً. لا تنظر للكتلة الكبيرة دفعة واحدة، بل قسمها لأجزاء صغيرة يسهل فهمها.`;
    } else if (mode === 'study_plan') {
      reply = `### 📝 خطة مراجعة سريعة وعملية (${topicLabel}):

- **المرحلة 1 (20 دقيقة): القراءة السريعة والتلخيص**
  - تصفح العناوين الرئيسية، الرسوم التوضيحية، وأهم التعريفات المحددة.
- **المرحلة 2 (30 دقيقة): حل التمارين والتطبيق العملي**
  - تدرب على حل تمرينين على الأقل بدون النظر إلى الإجابة النموذجية.
- **المرحلة 3 (10 دقائق): الاختبار الذاتي السريع**
  - افتح محاكي الامتحانات التفاعلي في النظام وأجب عن الكويز السريع للتأكد من ثبات المعلومة.`;
    } else {
      // General question answering
      reply = `بناءً على تحليلي لمحتوى **${topicLabel}** في سياق استفسارك ("${prompt}"):

- **الإجابة المباشرة:** الفكرة الأساسية ترتكز على تنظيم الخطوات وتحقيق التوازن بين الدقة والسرعة.
- **التطبيق في الاختبارات:** ينصح بذكر الخطوات التفصيلية ورسم المخطط إن كان السؤال مقالياً، أو تتبع القيم بعناية إذا كان السؤال اختيارياً (MCQ).
- **للمزيد من التوسع:** يمكنك الضغط على زر "فتح في Google NotebookLM" بالأسفل لاستيراد مصادرك المباشرة وصناعة Notebook مخصص على حسابك في جوجل.`;
    }

    return NextResponse.json({
      success: true,
      reply,
      topic: topicLabel,
      notebookLmUrl: 'https://notebook.google.com'
    });
  } catch (e: any) {
    return NextResponse.json({ success: false, error: e.message }, { status: 500 });
  }
}
